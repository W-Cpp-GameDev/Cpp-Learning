#include<iostream>
using namespace std;
//对象的初始化和清理
//1.构造函数，进行初始化
//2.析构函数，进行清理
//先创建一个类
class Person

{
	//构造函数注意事项
	//1.函数名必须和类一致
	//2.可以有参可以无参，因此可以发生重载
	//3.编译器会自动调用，且只调用一次
	//4.如果自己不写，编译器会自己创建，但是空实现
	//5.不用写返回值，void也不用写
public:
	Person()//构造函数可以有参数也可以无参
	{
		cout << "Person构造函数的调用" << endl;
	}
	//析构函数注意事项
	//1.函数名必须和类一致并在函数名前加上~
	//2.必须无参,所以不可以发生重载
	//3.对象在销毁前，编译器会自动调用,且只调用一次
	//4.如果自己不写，编译器会自己创建，但是空实现
	//5.不用写返回值，void也不用写
	~Person()
	{
		cout << "析构函数的调用" << endl;
	}
};
void print()
{
	Person p;//栈区,print执行完毕后，自动释放这个对象
}
int main()
{
	print();
	Person p;
	system("pause");
	return 0;

}